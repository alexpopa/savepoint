// Create or refresh the local AgentTester account used for browser checks. Local D1 only.
// Needs the dev server (npm run dev). Safe to re-run; --reset clears the account's activity first.
//   npm run test-account
//   npm run test-account -- --reset
// Docs: docs/browser-testing.md. Credentials land in docs/agent-test-account.local.md (gitignored).
import { pbkdf2Sync, randomBytes, randomUUID } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { appFetch, baseUrl, d1, findAccount, lit, mintSession, projectRoot } from "./local-dev.mjs";

const displayName = "AgentTester";
const email = "agent.tester@savepoint.test";
const friendName = "CozyCritic";
const credentialsPath = path.join(projectRoot, "docs/agent-test-account.local.md");
// Real IGDB games with covers, so game details, scores, and favorites all work.
const seedGames = [113112, 14593, 26226, 119133, 25076, 1942, 7346, 11133, 26192, 17000, 103298, 36926];

// Match app/auth.ts: PBKDF2-SHA-256, 100,000 iterations, 16-byte salt, 32-byte key.
function hashPassword(password) {
  const salt = randomBytes(16);
  return `pbkdf2_sha256$100000$${salt.toString("hex")}$${pbkdf2Sync(password, salt, 100_000, 32, "sha256").toString("hex")}`;
}

try { await fetch(baseUrl); }
catch { console.error(`The dev server is not reachable at ${baseUrl}. Start it with npm run dev.`); process.exit(1); }

const saved = existsSync(credentialsPath) ? readFileSync(credentialsPath, "utf8").match(/^- Password: `([^`]+)`$/m)?.[1] : undefined;
const password = saved || randomBytes(12).toString("base64url");
const now = Date.now();
let account = findAccount(displayName);
if (account) {
  d1(`UPDATE accounts SET email = ${lit(email)}, password_hash = ${lit(hashPassword(password))}, email_verified_at = COALESCE(email_verified_at, ${now}) WHERE user_id = ${lit(account.userId)}`);
} else {
  d1(`INSERT INTO accounts (user_id, email, display_name, is_public, password_hash, email_verified_at)
    VALUES (${lit(randomUUID())}, ${lit(email)}, ${lit(displayName)}, 1, ${lit(hashPassword(password))}, ${now})`);
  account = findAccount(displayName);
}
const userId = account.userId;

if (process.argv.includes("--reset")) {
  d1(`DELETE FROM library_items WHERE user_id = ${lit(userId)};
    DELETE FROM game_ratings WHERE user_id = ${lit(userId)};
    DELETE FROM game_favorites WHERE user_id = ${lit(userId)};
    DELETE FROM challenges WHERE creator_id = ${lit(userId)} OR recipient_id = ${lit(userId)};
    UPDATE accounts SET is_public = 1 WHERE user_id = ${lit(userId)}`);
  console.log("Reset AgentTester's library, scores, favorites, and challenges.");
}

// An accepted friendship with a seeded player gives the timeline and friend-only features real data.
const friend = findAccount(friendName);
if (friend) {
  const [low, high] = [userId, friend.userId].sort();
  d1(`INSERT INTO friendships (user_low, user_high, requester_id, status, created_at)
    VALUES (${lit(low)}, ${lit(high)}, ${lit(userId)}, 'accepted', ${now})
    ON CONFLICT(user_low, user_high) DO UPDATE SET status = 'accepted'`);
}

const session = mintSession(displayName);
const { body } = await appFetch(session, "/api/library");
const owned = new Set((body.games ?? []).map((game) => game.igdbId));
let added = 0;
for (const igdbId of seedGames.filter((id) => !owned.has(id))) {
  const details = await appFetch(null, `/api/igdb/games/${igdbId}`);
  const platformId = details.body.game?.platformOptions?.[0]?.id;
  if (platformId === undefined) { console.warn(`Skipped IGDB ${igdbId}: ${details.body.error ?? "no platforms"}`); continue; }
  const result = await appFetch(session, "/api/library", { method: "POST", body: JSON.stringify({ igdbId, platformId }) });
  if (result.ok) added++; else console.warn(`Skipped IGDB ${igdbId}: ${result.body.error ?? result.status}`);
}

writeFileSync(credentialsPath, `# AgentTester local credentials

Local development database only. This file is gitignored; never commit it or reuse this password anywhere else.
Regenerated by \`npm run test-account\`, which keeps the existing password. See [browser testing](browser-testing.md).

- Display name: \`${displayName}\`
- Email: \`${email}\`
- Password: \`${password}\`
- Account ID: \`${userId}\`
- Profile: ${baseUrl}/users/${displayName}
- Friend: ${friend ? `\`${friendName}\` (accepted)` : "none; CozyCritic is missing from this database"}
`);

console.log(`AgentTester ready at ${baseUrl}: ${owned.size + added} games (${added} added). Friend: ${friend ? friendName : "none"}.`);
console.log(`Credentials: ${path.relative(projectRoot, credentialsPath)}`);
